"""Hold every function in the pinned Python package to a named counterpart in the Rust port.

A port is read once and then trusted forever, which is how a function quietly goes missing: nothing
fails, because nothing was ever checking that it exists. This walks the pinned source with `ast`,
looks each function up in `scripts/json_repair_parity.toml`, and fails when one is unmapped, when a
mapping points at a Rust item that is not there, or when the ledger names a Python function that no
longer exists.

The ledger's `note` field is the audit: what the Rust does differently and why, or that it does not.
An entry with no counterpart must say what happened to it — inlined, split, or deliberately absent.

    .venv/bin/python scripts/check_json_repair_parity.py           # the gate
    .venv/bin/python scripts/check_json_repair_parity.py --skeleton  # a starting ledger
"""

from __future__ import annotations

import ast
import pathlib
import re
import sys
import tomllib

sys.path.insert(0, str(pathlib.Path(__file__).parent))

ROOT = pathlib.Path(__file__).parent.parent
RUST = ROOT / "crates" / "dsrust-json-repair" / "src"
LEDGER = ROOT / "scripts" / "json_repair_parity.toml"

#: How long a note has to be before it counts as one. A crude floor, and it is there because the
#: obvious way to satisfy a "must have a note" rule is to write "ported" 149 times.
MEANINGFUL_NOTE = 30


def package() -> pathlib.Path:
    """The pinned package, read from the installed one rather than a checkout.

    `generate_json_repair_upstream_fixture.py` verifies the two are byte-identical before it
    records anything, so this needs no clone and no network to run.
    """
    from pins import require

    require("json_repair")
    import json_repair

    return pathlib.Path(json_repair.__file__).parent


def python_symbols() -> dict[str, str]:
    """Every function and class in the pinned package, as `module.py::name`."""
    root = package()
    found = {}
    for path in sorted(root.rglob("*.py")):
        module = str(path.relative_to(root))
        for node in ast.walk(ast.parse(path.read_text())):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                found[f"{module}::{node.name}"] = signature(node)
            elif isinstance(node, ast.ClassDef):
                found[f"{module}::{node.name}"] = "class"
    return found


def signature(node: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    """The parameter list, so a changed default or a new keyword shows up as drift."""
    arguments = node.args
    positional = [argument.arg for argument in arguments.posonlyargs + arguments.args]
    defaults = [ast.unparse(default) for default in arguments.defaults]
    padded = [None] * (len(positional) - len(defaults)) + defaults
    parts = [name if default is None else f"{name}={default}" for name, default in zip(positional, padded)]
    if arguments.vararg:
        parts.append(f"*{arguments.vararg.arg}")
    for keyword, default in zip(arguments.kwonlyargs, arguments.kw_defaults):
        parts.append(keyword.arg if default is None else f"{keyword.arg}={ast.unparse(default)}")
    if arguments.kwarg:
        parts.append(f"**{arguments.kwarg.arg}")
    return "(" + ", ".join(parts) + ")"


def rust_source() -> str:
    return "\n".join(path.read_text() for path in RUST.rglob("*.rs"))


def defines(source: str, item: str) -> bool:
    """Whether the Rust names `item` as a function, type, constant or variant.

    A `Type::method` mapping is satisfied when both halves are defined, since the method is inside
    an `impl` block the type's name does not appear on.
    """
    return all(names(source, part) for part in item.split("::"))


def names(source: str, item: str) -> bool:
    pattern = rf"\b(fn|struct|enum|trait|type|const|impl)\s+{re.escape(item)}\b|^\s*{re.escape(item)}[({{,]"
    return re.search(pattern, source, re.MULTILINE) is not None


def skeleton(symbols: dict[str, str], source: str) -> str:
    """A ledger to start from: every symbol, with a guess at its counterpart."""
    lines = ["# Generated by --skeleton; every `note` still has to be written by a reader.\n"]
    for name, shape in symbols.items():
        guess = name.split("::")[1].lstrip("_")
        rust = guess if defines(source, guess) else ""
        lines.append(
            f"[[symbol]]\nname = {name!r}\npython = {shape!r}\nrust = {rust!r}\nnote = \"\"\n"
        )
    return "\n".join(lines)


def main() -> int:
    symbols = python_symbols()
    source = rust_source()

    if "--skeleton" in sys.argv:
        print(skeleton(symbols, source))
        return 0

    if not LEDGER.exists():
        raise SystemExit(f"{LEDGER} is missing — write it, or start from --skeleton")
    ledger = tomllib.loads(LEDGER.read_text())["symbol"]
    mapped = {entry["name"]: entry for entry in ledger}

    problems = []
    for name, shape in symbols.items():
        entry = mapped.get(name)
        if entry is None:
            problems.append(f"{name}{shape} has no ledger entry")
            continue
        if entry["python"] != shape:
            problems.append(f"{name}: signature moved, ledger says {entry['python']} and the pin says {shape}")
        if entry["rust"] and not defines(source, entry["rust"]):
            problems.append(f"{name}: ledger names `{entry['rust']}`, which the Rust does not define")
        if not entry["rust"] and not entry["note"]:
            problems.append(f"{name}: no counterpart and no reason given")
        # **Every** entry needs a note, not only the absences. A mapping on its own says a Rust
        # function of about that name exists — it would pass against a body that returns the wrong
        # answer, and fifteen defects were found by reading those bodies after this file was
        # written, none of which it could see. The note is where the reading is recorded, so a
        # blank one means "nobody has compared these two" and has to fail.
        elif len(entry["note"].strip()) < MEANINGFUL_NOTE:
            problems.append(
                f"{name}: no note, or too short to be one — say what the Rust does differently, "
                f"or what it took to be sure it does not"
            )
    for name in mapped.keys() - symbols.keys():
        problems.append(f"{name}: in the ledger and not in the pinned source")

    for problem in sorted(problems):
        print(f"  {problem}", file=sys.stderr)
    if problems:
        print(f"\nparity: {len(problems)} problems over {len(symbols)} Python symbols", file=sys.stderr)
        return 1

    ported = sum(1 for entry in ledger if entry["rust"])
    print(f"  parity: {len(symbols)} Python symbols, {ported} with a named Rust counterpart")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

"""Run the upstream project's own test suite and record every call it makes.

The cases in `json_repair_corpus.py` are ones I chose by reading the library, and a case list is
only ever as good as the reader. Upstream ships fourteen test files and some two hundred and thirty
direct `repair_json(input) == expected` assertions, written by the people who wrote the heuristics
and grown one bug report at a time. Those are better cases than mine.

They are **recorded rather than transcribed**. A `conftest.py` dropped into the checkout wraps
`repair_json` before pytest imports any test module, so every call the suite makes — its input, its
keyword arguments, and what came back — is written down as it happens. Transcribing them by hand is
the failure this repo has hit before: an expectation copied slightly wrong reads exactly like the
original until something reaches it.

    .venv/bin/python scripts/generate_json_repair_upstream_fixture.py
"""

from __future__ import annotations

import json
import pathlib
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))

from pins import PINS, require  # noqa: E402

ROOT = pathlib.Path(__file__).parent.parent
CHECKOUT = ROOT / "target" / "json-repair-upstream"
OUT = (
    ROOT
    / "crates"
    / "dsrust-json-repair"
    / "tests"
    / "conformance"
    / "json_repair_upstream.json"
)
RECORDING = CHECKOUT / "recorded-calls.jsonl"
TAG = f"v{PINS['json_repair']}"

#: Wraps the entry point before pytest imports a single test module, so `from ... import
#: repair_json` in each of them binds the recorder rather than the original.
CONFTEST = '''
"""Generated by scripts/generate_json_repair_upstream_fixture.py. Not upstream's file."""
import json, os, pathlib
import pytest
import src.json_repair.json_repair as module


@pytest.fixture
def benchmark():
    """Stands in for pytest-benchmark, which is not installed and is not what this run is for.

    The fourteen tests in `test_performance.py` are timings, and their *inputs* are as much a case
    as any other test's — a two-hundred-kilobyte reply, a string with a thousand comma fragments.
    Skipping them would drop exactly the shapes no hand-written corpus contains.
    """

    def run(function, *args, **kwargs):
        return function(*args, **kwargs)

    run.pedantic = lambda function, args=(), kwargs=None, **_: function(*args, **(kwargs or {}))
    return run

_out = pathlib.Path(os.environ["JSON_REPAIR_RECORDING"])
_original = module.repair_json


def repair_json(json_str="", *args, **kwargs):
    outcome = {}
    try:
        result = _original(json_str, *args, **kwargs)
    except BaseException as error:
        outcome = {"ok": False, "error": type(error).__name__, "message": str(error)}
        raise
    else:
        outcome = {"ok": True, "result": _describe(result, kwargs)}
        return result
    finally:
        # `json_fd` reads a file and `schema` needs a validator plugged in; neither is a call the
        # Rust entry point can be handed, and a fixture holding one would be untestable rather than
        # merely uncovered.
        #
        # Anything *else* unrecognised drops the case rather than being filtered out of the record.
        # `repair_json` forwards `**json_dumps_args` to `json.dumps`, so a call with
        # `ensure_ascii=False` produces different bytes — and a recorder that kept the result while
        # quietly dropping the argument writes a case that looks comparable and is not.
        if not kwargs.get("json_fd") and kwargs.get("schema") is None and not args:
            unknown = set(kwargs) - _SUPPORTED - _NOT_A_DUMPS_ARG
            record = (
                {"input": json_str, "kwargs": _clean(kwargs)} | outcome
                if not unknown
                else {"skipped": sorted(unknown), "input": json_str}
            )
            with _out.open("a") as handle:
                handle.write(json.dumps(record) + "\\n")


def _clean(kwargs):
    return {key: value for key, value in kwargs.items() if key in _SUPPORTED}


_SUPPORTED = {"return_objects", "skip_json_loads", "logging", "stream_stable", "strict", "ensure_ascii"}
_NOT_A_DUMPS_ARG = {"json_fd", "schema", "schema_repair_mode", "chunk_length"}


def _describe(result, kwargs):
    """What came back, read off the arguments rather than guessed from the type.

    `return_objects=True` answering with a *string* is indistinguishable by type from the repaired
    text the default returns, and guessing put `repair_json('("x")', return_objects=True)` — whose
    answer is the value `x` — into the fixture as the text `x`, which is what `json.dumps` would
    have written as `"x"`. Only the call site knows which it was.
    """
    if kwargs.get("logging"):
        value, log = result
        return {"value": json.dumps(value), "log": log}
    if kwargs.get("return_objects"):
        return {"value": json.dumps(result)}
    return {"text": result}


module.repair_json = repair_json
'''


def checkout() -> None:
    """The upstream repository at the pinned tag, cloned once."""
    if (CHECKOUT / "src" / "json_repair").is_dir():
        return
    CHECKOUT.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        ["git", "clone", "--quiet", "--depth", "1", "--branch", TAG,
         "https://github.com/mangiucugna/json_repair.git", str(CHECKOUT)],
        check=True,
    )


def check_the_checkout_is_the_pinned_source() -> None:
    """The tag must be byte-identical to the package the rest of the fixtures were generated from.

    A test suite from one version held against a port of another is a comparison that looks like
    conformance and is not.
    """
    import json_repair

    installed = pathlib.Path(json_repair.__file__).parent
    cloned = CHECKOUT / "src" / "json_repair"
    difference = subprocess.run(
        ["diff", "-r", "--exclude=__pycache__", str(cloned), str(installed)],
        capture_output=True,
        text=True,
    )
    if difference.returncode != 0:
        raise SystemExit(
            f"the {TAG} checkout differs from the installed package:\n{difference.stdout[:2000]}"
        )


def run_the_suite() -> tuple[int, str]:
    (CHECKOUT / "conftest.py").write_text(CONFTEST)
    RECORDING.unlink(missing_ok=True)
    RECORDING.touch()
    completed = subprocess.run(
        [sys.executable, "-m", "pytest", "tests", "-q", "--continue-on-collection-errors", "-p", "no:cacheprovider"],
        cwd=CHECKOUT,
        capture_output=True,
        text=True,
        env={**dict(__import__("os").environ), "JSON_REPAIR_RECORDING": str(RECORDING)},
    )
    return completed.returncode, completed.stdout.strip().splitlines()[-1] if completed.stdout else ""


def collect() -> tuple[list[dict], list[dict]]:
    """The comparable calls, and the ones dropped for carrying an argument this crate has no room for."""
    seen, cases, skipped = set(), [], []
    for line in RECORDING.read_text().splitlines():
        call = json.loads(line)
        if "skipped" in call:
            skipped.append(call)
            continue
        key = (call["input"], json.dumps(call["kwargs"], sort_keys=True))
        if key in seen:
            continue
        seen.add(key)
        cases.append(call)
    return cases, skipped


def check_the_corpus_discriminates(cases: list[dict]) -> None:
    if len(cases) < 200:
        raise SystemExit(f"only {len(cases)} recorded calls — the suite cannot have run")

    malformed = sum(1 for case in cases if not valid_json(case["input"]))
    if malformed < len(cases) * 0.5:
        raise SystemExit(f"only {malformed}/{len(cases)} malformed — this is not a repair corpus")

    # Upstream exercises the options through the same entry point, and a recording that lost them
    # would be a fixture testing the default arguments and calling it the suite.
    for option in ("skip_json_loads", "stream_stable", "strict", "return_objects"):
        if not any(case["kwargs"].get(option) for case in cases):
            raise SystemExit(f"no recorded call sets {option}")


def valid_json(text: str) -> bool:
    try:
        json.loads(text)
    except ValueError:
        return False
    return True


def main() -> None:
    version = require("json_repair")
    checkout()
    check_the_checkout_is_the_pinned_source()
    status, summary = run_the_suite()
    cases, skipped = collect()
    check_the_corpus_discriminates(cases)

    OUT.parent.mkdir(parents=True, exist_ok=True)
    header = {
        "source": f"the json_repair {TAG} test suite, run against json_repair {version}",
        "what": (
            "Every call upstream's own tests make to repair_json, with what came back — recorded "
            "while the suite ran rather than transcribed from its source. The suite's own pass or "
            "fail is not the point; the calls are."
        ),
        "pytest": summary,
    }
    lines = [json.dumps(header, ensure_ascii=False)[:-1] + ', "cases": [']
    lines += [
        " " + json.dumps(case, ensure_ascii=False) + ("," if index < len(cases) - 1 else "")
        for index, case in enumerate(cases)
    ]
    lines.append("]}")
    OUT.write_text("\n".join(lines) + "\n")

    refused = sum(1 for case in cases if not case["ok"])
    print(f"  pytest: {summary} (exit {status})", file=sys.stderr)
    print(f"  wrote {OUT} — {len(cases)} distinct calls, {refused} raising", file=sys.stderr)
    if skipped:
        arguments = sorted({name for call in skipped for name in call["skipped"]})
        print(f"  {len(skipped)} calls dropped, carrying {arguments}", file=sys.stderr)
    print(f"  {OUT.stat().st_size // 1024} KiB", file=sys.stderr)


if __name__ == "__main__":
    main()

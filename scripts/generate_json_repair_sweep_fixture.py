"""A bounded, committed sweep of the fuzz grammar, run through `json_repair` and written down.

`scripts/fuzz_json_repair.py` writes a campaign artifact that is deliberately not in git, and that
is right for twenty thousand strings. It is also why the crate's strongest oracle is *absent* from
every mutation run: `tests/fuzz.rs` skips when the corpus is not there, and cargo-mutants copies a
tree that never has it. Measured on the first whole-crate run, `lookahead.rs` lost 131 of its 139
viable mutants — a file of pure lookahead helpers that a hundred hand-named cases cannot reach.

So this is the same grammar, at a fixed seed and a fixed count, recorded as a golden like every
other fixture in this repo. The difference from `json_repair.json` is only where the cases come
from: drawn rather than named. Both are generated by running the pinned library, and neither is
written by hand.

The **log** is recorded with each case, and it is what makes this worth its size: a value says
where a parse arrived, the log says which branch took it there.

    .venv/bin/python scripts/generate_json_repair_sweep_fixture.py
"""

from __future__ import annotations

import json
import pathlib
import random
import sys

sys.path.insert(0, str(pathlib.Path(__file__).parent))

import json_repair  # noqa: E402
from fuzz_json_repair import reply, valid_json  # noqa: E402
from pins import require  # noqa: E402

OUT = (
    pathlib.Path(__file__).parent.parent
    / "crates"
    / "dsrust-json-repair"
    / "tests"
    / "conformance"
    / "json_repair_sweep.json"
)

#: Fixed, so the fixture is a golden and not a new campaign every time it is regenerated. Five
#: hundred rather than the twenty thousand the campaign runs: this exists so a mutation run can see
#: a differential oracle at all, and a fixture an order of magnitude larger than every other one in
#: the repo is a cost paid on every clone.
SEED = 20260801
COUNT = 500


def run(text: str) -> dict[str, object]:
    try:
        value, log = json_repair.loads(text, logging=True)
    except Exception as error:  # noqa: BLE001 — a refusal is part of the record
        return {"ok": False, "error": type(error).__name__}
    return {"ok": True, "dumps": json.dumps(value), "log": log}


def check_the_sweep_discriminates(cases: list[dict]) -> None:
    """Refuse to write a sweep that would pass against a parser doing almost nothing."""
    malformed = sum(1 for case in cases if not valid_json(case["input"]))
    if malformed < len(cases) * 0.8:
        raise SystemExit(f"only {malformed}/{len(cases)} malformed — most never reach the repairs")

    empty = sum(1 for case in cases if case.get("dumps") == '""')
    if empty > len(cases) * 0.2:
        raise SystemExit(f"{empty}/{len(cases)} answered '' — the grammar mostly produces nothing")

    # A sweep that repairs nothing pins no branch, which is the whole reason for recording the log.
    logged = sum(len(case.get("log", [])) for case in cases)
    if logged < len(cases):
        raise SystemExit(f"only {logged} logged repairs over {len(cases)} cases")

    distinct = {entry["text"] for case in cases for entry in case.get("log", [])}
    if len(distinct) < 20:
        raise SystemExit(f"only {len(distinct)} distinct repairs — the grammar is too narrow")


def main() -> None:
    require("json_repair")
    rng = random.Random(SEED)
    cases, seen = [], set()
    while len(cases) < COUNT:
        text = reply(rng)
        if text in seen:
            continue
        seen.add(text)
        cases.append({"input": text} | run(text))

    check_the_sweep_discriminates(cases)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    # One case per line: pretty-printing five thousand log entries triples the file for nothing,
    # and a line per case still diffs readably when the grammar changes.
    header = {
        "source": f"json_repair {version()}, CPython {sys.version.split()[0]}",
        "what": (
            "A fixed-seed sweep of the fuzz grammar in scripts/fuzz_json_repair.py, with what "
            "json_repair answered and every repair it logged getting there. Committed because the "
            "campaign corpus is not, and a mutation run that cannot see the differential oracle "
            "measures a suite nobody actually relies on."
        ),
        "seed": SEED,
    }
    lines = [json.dumps(header, ensure_ascii=False)[:-1] + ', "cases": [']
    lines += [
        " " + json.dumps(case, ensure_ascii=False) + ("," if index < len(cases) - 1 else "")
        for index, case in enumerate(cases)
    ]
    lines.append("]}")
    OUT.write_text("\n".join(lines) + "\n")
    logged = sum(len(case.get("log", [])) for case in cases)
    distinct = {entry["text"] for case in cases for entry in case.get("log", [])}
    refused = sum(1 for case in cases if not case["ok"])
    print(f"  wrote {OUT} — {len(cases)} cases, {refused} refused", file=sys.stderr)
    print(f"  {logged} logged repairs, {len(distinct)} distinct", file=sys.stderr)
    print(f"  {OUT.stat().st_size // 1024} KiB", file=sys.stderr)


def version() -> str:
    from importlib.metadata import version as installed

    return installed("json_repair")


if __name__ == "__main__":
    main()
